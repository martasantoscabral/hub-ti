// ----- Inserir títulos de categoria no catálogo -----
function inserirTitulosCategorias() {
  const grid = document.getElementById("grid_catalogo");
  if (!grid) return;

  // todos os cards
  const cards = Array.from(grid.querySelectorAll(".itemCatalogo"));

  // limpar grelha
  grid.innerHTML = "";

  //cards por categoria
  const grupos = {};

  cards.forEach(card => {
    const nome = card.querySelector(".plant-name").textContent.trim();
    const info = PLANT_INFO[nome];

    const categoria = info ? info.categoria : "Outras";

    if (!grupos[categoria]) grupos[categoria] = [];
    grupos[categoria].push(card);
  });

  // inserir título + cards
  for (const categoria of Object.keys(grupos)) {
    const titulo = document.createElement("div");
    titulo.className = "categoriaTitulo";
    titulo.innerHTML = `<h2>${categoria}</h2>`;

    grid.appendChild(titulo);

    grupos[categoria].forEach(card => grid.appendChild(card));
  }
}

inserirTitulosCategorias();

